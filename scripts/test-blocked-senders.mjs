import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
const exports = {};
new Function("exports", ts.transpileModule(readFileSync("lib/blocked-senders.ts", "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText)(exports);
const { normalizeBlockedSender, blockedSenderSource, managedBlockedSender, blockedSenderReplacement } = exports;
const sender = normalizeBlockedSender(" Sender@Example.COM ");
assert.deepEqual(sender, { type: "email", value: "sender@example.com" });
assert.deepEqual(normalizeBlockedSender("example.com"), { type: "domain", value: "example.com" });
for (const value of ["", "a@", "a@@example.com", "a..b@example.com", 'a"; discard;@example.com', "a\r\n@example.com", "*.example.com", "-example.com", "@example.com"]) assert.equal(normalizeBlockedSender(value), null);
const original = { id: "existing", name: "Original", kind: "advanced", source: "keep;", enabled: true, position: 0, updatedAt: "2026-10-06T00:00:00Z" };
const data = { mode: "rules", enabled: true, revision: 12, source: "", rules: [original] };
const rules = blockedSenderReplacement(data, { add: sender, mailbox: 'Junk "Safe"' });
assert.equal(rules.length, 2);
assert.deepEqual(rules[1], { id: original.id, name: original.name, kind: original.kind, source: original.source, enabled: true });
const rule = { ...rules[0], id: "managed", position: 0, updatedAt: original.updatedAt };
assert.deepEqual(managedBlockedSender(rule), sender);
assert.equal(managedBlockedSender({ ...rule, source: rule.source + "discard;" }), null);
assert.equal(managedBlockedSender({ ...rule, name: "Other" }), null);
const saved = { ...data, rules: [rule, original] };
assert.throws(() => blockedSenderReplacement(saved, { add: sender, mailbox: "Junk" }), /duplicate/);
assert.equal(blockedSenderReplacement(saved, { removeId: rule.id }).length, 1);
assert.throws(() => blockedSenderReplacement(saved, { removeId: original.id }), /invalid_request/);
assert.throws(() => blockedSenderReplacement({ ...data, mode: "advanced", source: "keep;" }, { add: sender, mailbox: "Junk" }), /legacy/);
assert.throws(() => blockedSenderReplacement({ ...data, rules: Array(50).fill(original) }, { add: sender, mailbox: "Junk" }), /limit/);
assert.ok(blockedSenderSource({ type: "domain", value: "example.com" }, "Junk").includes('address :domain :is "from" "example.com"'));
const ui = readFileSync("components/settings/LiveBlockedSenders.tsx", "utf8");
for (const guard of ["expectedRevision", "locked.current", "setUncertain(true)", "controller.signal.aborted", "ConfirmDialog", "SystemErrorNotice"]) assert.ok(ui.includes(guard));
assert.ok(!ui.includes("localStorage"));
console.log("PASS: validation, safe Sieve serialization, managed rule ownership, preservation, duplicates, limits and conflict guards");
