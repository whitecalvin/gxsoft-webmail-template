import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import React from "react";
import ts from "typescript";

const require = createRequire(import.meta.url);
const source = readFileSync(new URL("../components/ui/IconButton.tsx", import.meta.url), "utf8");
const exports = {};
const Button = () => null;
const Tooltip = () => null;
const mocks = { "./Button": { Button }, "./Tooltip": { Tooltip }, "./utils": { cn: (...values) => values.filter(Boolean).join(" ") } };
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX } }).outputText;
new Function("require", "exports", code)(name => mocks[name] ?? require(name), exports);
const ref = React.createRef();
let clicks = 0;
const icon = React.createElement("svg");
const tree = exports.IconButton.render({ label: "뉴스 폴더로 이동", icon, compact: true, className: "text-inherit", onClick: () => clicks++ }, ref);
assert.equal(tree.type, Tooltip);
assert.equal(tree.props.content, "뉴스 폴더로 이동");
assert.equal(tree.props.side, "bottom");
assert.match(tree.props.className, /shrink-0/);
const button = tree.props.children;
assert.equal(button.type, Button);
assert.equal(button.props.ref, ref);
assert.equal(button.props["aria-label"], "뉴스 폴더로 이동");
assert.equal(button.props.title, undefined);
assert.equal(button.props.children, icon);
assert.match(button.props.className, /size-8/);
button.props.onClick();
assert.equal(clicks, 1);
const dropdown = readFileSync(new URL("../components/ui/Dropdown.tsx", import.meta.url), "utf8");
assert.doesNotMatch(dropdown, /\btitle=/, "dropdown must not duplicate its caller's custom tooltip");
console.log("Icon button: custom tooltip, accessible label, ref, sizing and click preserved; dropdown has no native tooltip.");
