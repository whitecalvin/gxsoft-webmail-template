import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
const exports = {};
new Function("exports", ts.transpileModule(readFileSync("lib/mail-notifications.ts", "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText)(exports);
const { notificationAllowed, validQuietTime, NewMailDetector } = exports;
const settings = { weekends: false, quietStart: "22:00", quietEnd: "07:00", modes: { important: "instant", general: "instant" } };
assert.equal(validQuietTime("23:59"), true);
for (const time of ["24:00", "7:00", "", "12:60"]) assert.equal(validQuietTime(time), false);
const date = (hour, day = 6) => new Date(2026, 9, day, hour, 0);
assert.equal(notificationAllowed(settings, date(12), false), true);
assert.equal(notificationAllowed(settings, date(23), false), false);
assert.equal(notificationAllowed(settings, date(6), false), false);
assert.equal(notificationAllowed(settings, date(7), false), true);
assert.equal(notificationAllowed(settings, date(12, 10), false), false);
assert.equal(notificationAllowed({ ...settings, weekends: true }, date(12, 10), false), true);
assert.equal(notificationAllowed({ ...settings, modes: { ...settings.modes, general: "off" } }, date(12), false), false);
assert.equal(notificationAllowed({ ...settings, quietStart: "09:00", quietEnd: "17:00" }, date(12), false), false);
assert.equal(notificationAllowed({ ...settings, quietStart: "00:00", quietEnd: "00:00" }, date(12), false), true);
const detector = new NewMailDetector();
const mail = (id, time, unread = true) => ({ id, receivedAt: new Date(time).toISOString(), unread, starred: false });
assert.deepEqual(detector.observe("a", [mail("old", 1000)], 2000), []);
assert.equal(detector.observe("a", [mail("new", 3000), mail("old", 1000)], 4000).length, 1);
assert.deepEqual(detector.observe("a", [mail("new", 3000)], 5000), []);
assert.deepEqual(detector.observe("a", [mail("moved", 1000)], 6000), []);
assert.deepEqual(detector.observe("a", [mail("read", 6500, false)], 7000), []);
assert.deepEqual(detector.observe("b", [mail("new", 8000)], 9000), []);
detector.reset(); assert.deepEqual(detector.observe("b", [mail("newer", 10000)], 11000), []);
