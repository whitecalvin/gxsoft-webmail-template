import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
const source = readFileSync("lib/mail-shortcuts.ts", "utf8");
const exports = {};
new Function("exports", ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText)(exports);
const { normalizeShortcut, shortcutConflicts, ShortcutSequence } = exports;
const defaults = { compose: "C", search: "/", inbox: "G I", archive: "E", delete: "#", reply: "R", forward: "F" };
assert.equal(normalizeShortcut(" g   i "), "G I");
for (const key of ["", "Escape", "Ctrl+C", "G I A", "한", null]) assert.equal(normalizeShortcut(key), null);
assert.equal(shortcutConflicts(defaults), false);
assert.equal(shortcutConflicts({ ...defaults, reply: "C" }), true);
assert.equal(shortcutConflicts({ ...defaults, compose: "G" }), true);
const sequence = new ShortcutSequence();
assert.equal(sequence.match("c", defaults, 0), "compose");
assert.equal(sequence.match("G", defaults, 0), null);
assert.equal(sequence.match("i", defaults, 900), "inbox");
assert.equal(sequence.match("g", defaults, 1000), null);
assert.equal(sequence.match("i", defaults, 2001), null);
sequence.match("g", defaults, 3000); sequence.reset();
assert.equal(sequence.match("i", defaults, 3100), null);
assert.equal(sequence.match("#", defaults, 3200), "delete");
assert.equal(sequence.match("x", { ...defaults, compose: "X" }, 3300), "compose");
const runtime = readFileSync("components/layout/WorkspaceShortcuts.tsx", "utf8");
for (const guard of ["event.isComposing", "event.repeat", "event.ctrlKey", "event.metaKey", "event.altKey", "contenteditable", "saved.shortcuts.enabled", "pendingMutationIds", "uncertainMutationIds", "button.disabled", "[inert]"]) assert.ok(runtime.includes(guard), guard);
const reading = readFileSync("components/mail/ReadingPane.tsx", "utf8");
for (const action of ["reply", "forward", "delete"]) assert.ok(reading.includes(`data-mail-shortcut="${action}"`));
console.log("PASS: shortcut format, conflicts, sequence timeout/reset, customization and runtime safety guards");
