import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
const exports = {};
const code = ts.transpileModule(readFileSync("lib/mailbox-visibility.ts", "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
new Function("exports", code)(exports);
const child = { path: "dev/github", label: "github", mailbox: { id: "child" }, children: [] };
const parent = { path: "dev", label: "dev", mailbox: { id: "parent" }, children: [child] };
const nodes = [parent];
assert.deepEqual(exports.visiblePersonalFolderTree(nodes, ["parent"]), [child], "visible children survive hidden parent");
assert.deepEqual(exports.visiblePersonalFolderTree(nodes, ["child"]), [{ ...parent, children: [] }]);
assert.deepEqual(exports.visiblePersonalFolderTree(nodes, ["parent", "child"]), []);
assert.deepEqual(exports.visiblePersonalFolderTree([{ ...parent, mailbox: null }], ["child"]), []);
assert.equal(nodes[0].children[0], child, "does not mutate original mail tree");
const sidebar = readFileSync("components/layout/WorkspaceSidebar.tsx", "utf8");
assert.match(sidebar, /saved.inbox.hiddenSystemMailboxes/);
const tree = readFileSync("components/mail/PersonalFolderTree.tsx", "utf8");
assert.match(tree, /visiblePersonalFolderTree\(personalFolderTree\(mailboxes\), saved.inbox.hiddenMailboxIds\)/);
const ui = readFileSync("components/settings/MailboxVisibilitySettings.tsx", "utf8");
assert.match(ui, /draft.inbox\[field\]/);
assert.match(ui, /mailbox.role === null/);
assert.doesNotMatch(ui, /localStorage|changeFolder|fetch\(/);
console.log("mailbox visibility: independent children, immutable projection, saved SSR sidebar, shared account settings passed");
