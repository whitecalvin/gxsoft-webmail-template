import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
import { liveSearchFilter } from "../lib/tastemail/search-filter.ts";

const source = readFileSync(new URL("../components/mail/InboxContextMenu.tsx", import.meta.url), "utf8");
const tree = ts.createSourceFile("menu.tsx", source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
let actions, closeHandler;
function visit(node) { if (ts.isVariableDeclaration(node) && node.name.getText(tree) === "actions") actions = node.initializer; if (ts.isVariableDeclaration(node) && node.name.getText(tree) === "close") closeHandler = node.initializer; ts.forEachChild(node, visit); }
visit(tree); assert.ok(actions);
const closeJs = ts.transpileModule(`const close = ${closeHandler.getText(tree)};`, { compilerOptions: { target: ts.ScriptTarget.ES2022 } }).outputText;
let focused = 0, dismissed = 0;
const close = new Function("setPosition", "trigger", `${closeJs}; return close;`)(() => dismissed++, { current: { focus: () => focused++ } });
close(false);
assert.equal(focused, 0, "pointer action must not focus a drag tooltip");
close();
assert.equal(focused, 1, "keyboard dismissal restores the actual menu trigger");
assert.equal(dismissed, 2);
assert.match(source, /close\(event.detail === 0\)/);
assert.match(source, /button ref=\{trigger\}/);
const js = ts.transpileModule(`const managementOnly = false; const actions = ${actions.getText(tree)};`, { compilerOptions: { target: ts.ScriptTarget.ES2022 } }).outputText;
function make(activeFolder, blocked = false, folder = "inbox", mailboxId = "custom-id", mailboxName = "Work", current = activeFolder === folder) {
  const calls = [];
  const spy = name => (...args) => calls.push([name, ...args]);
  const menu = new Function("t", "Inbox", "Mail", "MailCheck", "RefreshCw", "onOpen", "refreshMailbox", "router", "setRead", "activeFolder", "refreshPending", "blocked", "unread", "folder", "Files", "Folder", "mailboxId", "mailboxName", "current", `${js}; return actions;`)(key => key, 0, 0, 0, 0, spy("open"), spy("refresh"), { push: spy("route") }, spy("read"), activeFolder, false, blocked, [{ id: "a" }, { id: "b" }], folder, 0, 0, mailboxId, mailboxName, current);
  return { menu, calls };
}
const inbox = make("inbox");
assert.equal(inbox.menu.some(item => item.label === "open"), false);
inbox.menu[0].run(); assert.deepEqual(inbox.calls, [["refresh"]]);
inbox.menu[2].run(); assert.deepEqual(inbox.calls.slice(1), [["read", "a", true], ["read", "b", true]]);
inbox.menu[1].run();
const query = inbox.calls.at(-1)[1].query.q;
assert.deepEqual(liveSearchFilter(query, [{ id: "inbox", role: "inbox", name: "Inbox" }]), { operator: "AND", conditions: [{ inMailbox: "inbox" }, { notKeyword: "$seen" }] });
const other = make("sent", true);
assert.equal(other.menu[3].disabled, true);
other.menu[3].run(); assert.equal(other.calls.length, 0);
other.menu[1].run(); assert.deepEqual(other.calls, [["open"]]);
console.log("inbox menu: open/refresh, unread search contract, current-page read and blocked write guard passed");
const all = make("all", false, "all");
assert.equal(all.menu.some(item => item.label === "open" || item.label === "openAll"), false);
all.menu[0].run();
assert.deepEqual(all.calls, [["refresh"]]);
all.menu[1].run();
assert.deepEqual(liveSearchFilter(all.calls.at(-1)[1].query.q, []), { notKeyword: "$seen" });
all.menu[2].run();
assert.deepEqual(all.calls.slice(-2), [["read", "a", true], ["read", "b", true]]);
const inactiveAll = make("inbox", true, "all");
inactiveAll.menu[1].run();
inactiveAll.menu[3].run();
assert.deepEqual(inactiveAll.calls, [["open"]]);
console.log("all-mail menu: all-account unread search, refresh, current-page read and inactive guards passed");
const custom = make("custom", false, "custom", "exact-id", 'Work/Long "name"');
assert.equal(custom.menu.some(item => item.label === "open" || item.label === 'Work/Long "name"'), false);
custom.menu[1].run();
assert.deepEqual(custom.calls.at(-1), ["route", { pathname: "/search", query: { q: "is:unread", mailboxId: "exact-id" } }]);
custom.menu[0].run(); assert.deepEqual(custom.calls.at(-1), ["refresh"]);
const inactiveCustom = make("custom", true, "custom", "other-id", "Other", false);
assert.equal(inactiveCustom.menu[0].label, "open");
assert.equal(inactiveCustom.menu.some(item => item.label === "Other"), false);
inactiveCustom.menu[0].run();
assert.deepEqual(inactiveCustom.calls, [["open"]]);
inactiveCustom.calls.length = 0;
inactiveCustom.menu[1].run(); inactiveCustom.menu[3].run();
assert.deepEqual(inactiveCustom.calls, [["open"]]);
assert.match(source, /activeCustomMailboxId === mailboxId/);
const searchSource = readFileSync(new URL("../components/search/LiveMailSearch.tsx", import.meta.url), "utf8");
assert.match(searchSource, /searchParams.get\("mailboxId"\)/);
assert.match(searchSource, /params.set\("mailboxId", folder.slice\(7\)\)/);
console.log("custom menu: exact mailbox search scope, refresh and other-mailbox write guard passed");
for (const folder of ["drafts", "sent", "archive", "spam", "trash", "starred"]) {
  const selected = make(folder, false, folder);
  assert.equal(selected.menu.some(item => item.label === "open"), false);
  selected.menu[0].run();
  assert.deepEqual(selected.calls.at(-1), ["refresh"]);
  selected.menu[1].run();
  const filter = liveSearchFilter(selected.calls.at(-1)[1].query.q, [{ id: `id-${folder}`, role: folder === "spam" ? "junk" : folder, name: folder }]);
  assert.deepEqual(filter, { operator: "AND", conditions: [folder === "starred" ? { hasKeyword: "$flagged" } : { inMailbox: `id-${folder}` }, { notKeyword: "$seen" }] });
  selected.menu[2].run();
  assert.deepEqual(selected.calls.slice(-2), [["read", "a", true], ["read", "b", true]]);
  const inactive = make("inbox", true, folder);
  assert.equal(inactive.menu[0].label, "open");
  inactive.menu[3].run();
  assert.equal(inactive.calls.length, 0);
}
console.log("all system folders: correct unread search scope, refresh and inactive write guards passed");
