import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import vm from "node:vm";
import ts from "typescript";
import React from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { personalFolderTree } from "../lib/personal-folder-tree.ts";
import * as visibility from "../lib/mailbox-visibility.ts";

const require = createRequire(import.meta.url);
const source = readFileSync(new URL("../components/mail/PersonalFolderTree.tsx", import.meta.url), "utf8");
const messages = JSON.parse(readFileSync(new URL("../messages/en.json", import.meta.url), "utf8"));
const mailbox = { id: "custom-id", role: null, name: "Work", totalEmails: 0, unreadEmails: 0, usedBytes: 1024 ** 2, quotaBytes: 10 * 1024 ** 3 };
function render(extra = {}, compact = false, display = { showMailboxCounts: true, showMailboxStorage: true }, kind) {
  const box = { ...mailbox, ...extra };
  const menus = [];
  const exports = {};
  const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, jsx: ts.JsxEmit.ReactJSX } }).outputText;
  vm.runInNewContext(code, { exports, require: name => {
    if (name === "next-intl") return { useLocale: () => "en", useTranslations: namespace => (key, values = {}) => {
      const template = messages[namespace][key]; assert.equal(typeof template, "string");
      return template.replace(/\{(\w+)\}/g, (_, field) => String(values[field]));
    } };
    if (name === "@/context/settings-context") return { useSettings: () => ({ saved: { inbox: display } }) };
    if (name === "@/context/mail-context") return { useMail: () => ({ mailboxes: [box], folderChangePending: false, folderChangeUncertain: false }) };
    if (name === "@/lib/personal-folder-tree") return { personalFolderTree };
    if (name === "@/lib/mailbox-visibility") return visibility;
    if (name === "./PersonalFolderIcon") return { PersonalFolderIcon: () => null, kindKey: (account, id) => `${account}:${id}` };
    if (name === "@/context/mailbox-icon-context") return { useInitialMailboxIcons: () => kind ? ({ [":" + box.id]: kind }) : ({}), useServerMailboxIcons: () => ({ required: false, matched: false }) };
    if (name === "@/context/toast-context") return { useToast: () => ({ success() {}, error() {} }) };
    if (name === "@/components/ui/Tooltip") return { Tooltip: props => React.createElement("span", { className: props.className, "data-tooltip": props.content }, props.children) };
    if (name === "@/lib/personal-folder-drag") return { folderDropChange: () => null };
    if (name === "./PersonalFolderDeleteButton") return { PersonalFolderDeleteButton: () => null };
    if (name === "./PersonalFolderManager") return { PersonalFolderManager: () => null };
    if (name === "./InboxContextMenu") return { InboxContextMenu: props => { menus.push(props); return props.children; } };
    return require(name);
  } });
  const html = renderToStaticMarkup(React.createElement(exports.PersonalFolderTree, { compact, activeId: box.id, onOpen: () => {}, activeClass: "active", idleClass: "idle" }));
  return { html, menus };
}
const valid = render();
assert.match(valid.html, /data-mailbox-kind="mailbox"/);
assert.match(valid.html, /data-mailbox-kind-label="mailbox"/);
assert.match(render({}, false, { showMailboxCounts: false, showMailboxStorage: false }, "folder").html, /data-mailbox-kind-label="folder"/);
assert.match(valid.html, /1 MiB \/ 10 GiB/);
assert.doesNotMatch(valid.html, /\stitle=/, "folder tree must not use native tooltips");
assert.match(valid.html, /data-tooltip="Move Work/);
assert.equal(valid.menus[0].mailboxId, "custom-id");
assert.equal(valid.menus[0].folder, "custom");
assert.equal(valid.menus[0].deleteDisabled, false);
assert.equal(typeof valid.menus[0].onDelete, "function");
assert.equal(render({ totalEmails: 1 }).menus[0].deleteDisabled, true);
assert.doesNotMatch(render({ usedBytes: null }).html, /MiB/);
assert.doesNotMatch(render({ quotaBytes: null }).html, /MiB/);
assert.equal(typeof render({}, true).menus[0].onDelete, "function");
assert.equal(valid.menus[0].showTrigger, true);
assert.equal(valid.menus[0].managementActions.length, 4);
assert.equal(valid.menus[0].managementActions[0].label, messages.personalFolders.move);
assert.equal(valid.menus[0].managementActions[0].disabled, true, "missing account disables movement");
assert.equal(valid.menus[0].managementActions[3].disabled, false);
const nested = render({ name: "Parent/Child" });
assert.equal(nested.menus[0].managementOnly, true);
assert.equal(nested.menus[0].managementActions.length, 2);
assert.equal(nested.menus[0].onDelete, undefined);
assert.match(nested.html, /data-mailbox-kind-label="folder"/, "virtual parent has an explicit folder label");
assert.match(render({ name: "Parent/Child" }).html, /1 MiB \/ 10 GiB/);
const hidden = render({}, false, { showMailboxCounts: false, showMailboxStorage: false }).html;
assert.doesNotMatch(hidden, /MiB/);
assert.doesNotMatch(hidden, /<span[^>]*>[^<]*unread/i);
assert.match(render({}, false, { showMailboxCounts: false, showMailboxStorage: true }).html, /MiB/);
assert.doesNotMatch(render({}, false, { showMailboxCounts: true, showMailboxStorage: false }).html, /MiB/);
console.log("custom sidebar: capacity, unknown-value guard, nested context menu and safe deletion passed");
