import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
import * as catalog from "../lib/mailbox-icon-catalog.mjs";

function load(file, imports) {
  const code = ts.transpileModule(readFileSync(file, "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
  const exported = {};
  new Function("require", "exports", code)(name => { if (!(name in imports)) throw new Error(name); return imports[name]; }, exported);
  return exported;
}
const contract = load("lib/tastemail/icon-preferences-contract.ts", { "../mailbox-icon-catalog.mjs": catalog });
const browser = load("lib/mailbox-icon-preferences.ts", { "./mailbox-icon-catalog.mjs": catalog });
const mapping = load("lib/mailbox-icon-snapshot.ts", { "./mailbox-icon-preferences": browser, "./tastemail/icon-preferences-contract": contract });
const { planIconPreferenceImport: plan } = load("lib/icon-preference-import.ts", { "./mailbox-icon-catalog.mjs": catalog, "./mailbox-icon-snapshot": mapping, "./tastemail/icon-preferences-contract": contract });
const owner = "owner@example.test";
const id = n => `00000000-0000-0000-0000-${String(n).padStart(12, "0")}`;
const profile = { type: "profile" }, mailbox = { type: "mailbox", id: id(1) }, junk = { type: "system", role: "junk" }, shared = { type: "sharedAccount", id: id(2) };
const base = { revision: 0, catalogVersion: contract.ICON_CATALOG_VERSION, availableTargets: [profile, mailbox, junk, shared], preferences: [], defaultIcon: "default", defaultDisplayKind: "mailbox" };
const key = target => mapping.iconPreferenceKey(owner, target);
const kindKey = target => `gxmail:folder-kind:v1:${encodeURIComponent(owner)}:${target.id}`;
const local = { [key(profile)]: "shopping", [key(mailbox)]: "emoji:grinning", [kindKey(mailbox)]: "folder", [key(junk)]: "phosphor:acorn", [key(shared)]: "lucide:heart", [browser.accountIconKey("foreign@example.test")]: "emoji:100" };
const before = JSON.stringify(local);
const imported = plan(" OWNER@EXAMPLE.TEST ", base, local);
assert.equal(imported.changes.length, 4);
assert.ok(contract.validIconChanges(imported.changes));
assert.equal(imported.changes.find(entry => entry.target.type === "profile").icon, "lucide:shopping-bag");
assert.equal(imported.changes.find(entry => entry.target.type === "mailbox").displayKind, "folder");
assert.equal(JSON.stringify(local), before, "planning must not change browser data");
assert.equal(plan("foreign@example.test", base, local).changes.length, 1, "only that exact account's keys are considered");
assert.equal(plan(owner, { ...base, preferences: [{ target: mailbox, icon: "lucide:mail", displayKind: "mailbox" }] }, local).changes.some(entry => entry.target.type === "mailbox"), false);
assert.equal(plan(owner, base, { [kindKey(mailbox)]: "folder" }).changes[0].icon, "default");
assert.equal(plan(owner, base, { [kindKey(mailbox)]: "mailbox" }).changes.length, 0, "authoritative default needs no new preference slot");
for (const invalid of ["<svg/>", "emoji:missing", "https://example.test/icon.svg", 42]) assert.equal(plan(owner, base, { [key(profile)]: invalid }).skipped, 1);
assert.equal(plan(owner, base, { [kindKey(mailbox)]: "unknown" }).skipped, 1);
assert.equal(plan(owner, base, Object.create(local)).changes.length, 0, "inherited keys are not browser choices");
assert.equal(plan(owner, { ...base, catalogVersion: "unknown" }, local).blocked, "invalid_snapshot");
assert.equal(plan("", base, local).blocked, "invalid_snapshot");
const targets = Array.from({ length: 514 }, (_, n) => ({ type: "mailbox", id: id(n + 10) }));
const many = { ...base, availableTargets: [profile, ...targets] };
const bulkLocal = Object.fromEntries(targets.slice(0, 70).map(target => [key(target), "heart"]));
const first = plan(owner, many, bulkLocal);
assert.equal(first.changes.length, 64); assert.equal(first.remaining, 6);
assert.ok(contract.validIconChanges(first.changes));
const second = plan(owner, { ...many, revision: 1, preferences: first.changes }, bulkLocal);
assert.equal(second.changes.length, 6); assert.equal(second.remaining, 0);
const full = { ...many, preferences: targets.slice(0, 512).map(target => ({ target, icon: "lucide:mail" })) };
assert.equal(plan(owner, full, { [key(targets[513])]: "heart" }).blocked, "capacity");
const almostFull = { ...full, preferences: full.preferences.slice(0, 511) };
assert.equal(plan(owner, almostFull, { [key(targets[512])]: "heart", [key(targets[513])]: "heart" }).changes.length, 1);
console.log("icon import plan: canonical aliases, owner/target isolation, kind preservation, no writes/overwrite, validation and bounded confirmed batches passed");
